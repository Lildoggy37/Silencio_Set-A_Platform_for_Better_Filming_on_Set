import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { beforeEach, expect, test, vi } from 'vitest'
import { StockBoard } from './StockBoard'
import { AccountError } from '../api/accounts'

const api = vi.hoisted(() => ({ stocks: vi.fn(), stock: vi.fn(), movements: vi.fn(), stockWrite: vi.fn(), members: vi.fn() }))
vi.mock('../auth/AuthProvider', () => ({ useAuth: () => ({ resources: api, crews: { members: api.members }, refresh: vi.fn() }) }))
const row = { id: 'stock-1', crew_id: 'crew', name: '胶带', unit: '卷', stock_quantity: 5, lock_version: 1, manager_member_id: 'member-1', status: 'available', allowed_actions: ['change', 'authorize'] }
beforeEach(() => {
  vi.resetAllMocks()
  api.stocks.mockResolvedValue({ items: [row], total: 1, page: 1, page_size: 20 })
  api.stock.mockResolvedValue(row)
  api.members.mockResolvedValue({ items: [{ id: 'member-1', display_name: '美术同学', lock_version: 3 }], total: 1 })
  api.movements.mockResolvedValue({ items: [], total: 0, page: 1, page_size: 20 })
  api.stockWrite.mockResolvedValue({ resource: row, movement: null })
})
function start(canCreate = true) {
  render(<QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false, gcTime: 0 } } })}><StockBoard crewId="crew" userId="user" canCreate={canCreate} /></QueryClientProvider>)
}
async function openAction(name: string) {
  fireEvent.click(await screen.findByRole('button', { name: '查看耗材胶带' }))
  fireEvent.click(await screen.findByRole('button', { name }))
  return within(name === '库存管理权限' ? screen.getByRole('dialog') : screen.getByRole('button', { name: '核对库存操作' }).closest('[role="dialog"]') as HTMLElement)
}
test('read-only members see balance but never request private movements', async () => {
  api.stock.mockResolvedValue({ ...row, allowed_actions: [] })
  start(false); fireEvent.click(await screen.findByRole('button', { name: '查看耗材胶带' }))
  await screen.findByText('当前库存：5 卷')
  expect(screen.queryByRole('button', { name: '库存变动' })).toBeNull()
  expect(screen.queryByRole('button', { name: '登记耗材' })).toBeNull()
  expect(api.movements).not.toHaveBeenCalled()
})
test('create accepts zero initial balance and submits only after explicit confirmation', async () => {
  start(); fireEvent.click(screen.getByRole('button', { name: '登记耗材' }))
  const editor = within(screen.getByLabelText('耗材名称').closest('[role="dialog"]') as HTMLElement)
  fireEvent.change(editor.getByLabelText('耗材名称'), { target: { value: '电池' } })
  await editor.findByRole('option', { name: '美术同学' })
  fireEvent.change(editor.getByLabelText('耗材负责人'), { target: { value: 'member-1' } })
  await waitFor(() => expect(editor.getByRole('button', { name: '核对库存操作' }).hasAttribute('disabled')).toBe(false))
  fireEvent.click(editor.getByRole('button', { name: '核对库存操作' }))
  expect(api.stockWrite).not.toHaveBeenCalled()
  fireEvent.click(editor.getByRole('button', { name: '确认库存操作' }))
  await waitFor(() => expect(api.stockWrite).toHaveBeenCalledTimes(1))
  expect(api.stockWrite.mock.calls[0][1]).toMatchObject({ action: 'create', body: { name: '电池', initial_quantity: 0, manager_member_id: 'member-1' } })
})
test('issue uses a negative delta and unknown results reuse the original key', async () => {
  api.stockWrite.mockRejectedValueOnce(new AccountError('NETWORK_UNCONFIRMED'))
  start(); const editor = await openAction('库存变动')
  fireEvent.change(editor.getByLabelText('变动类型'), { target: { value: 'issue' } })
  fireEvent.change(editor.getByLabelText('变动数量'), { target: { value: '2' } })
  fireEvent.change(editor.getByLabelText('变动原因'), { target: { value: '拍摄布景' } })
  fireEvent.click(editor.getByRole('button', { name: '核对库存操作' })); fireEvent.click(editor.getByRole('button', { name: '确认库存操作' }))
  const retry = await editor.findByRole('button', { name: '用原库存请求重试' })
  await waitFor(() => expect(retry.classList.contains('ant-btn-loading')).toBe(false))
  fireEvent.click(retry)
  await waitFor(() => expect(api.stockWrite).toHaveBeenCalledTimes(2))
  expect(api.stockWrite.mock.calls[0][1]).toEqual(api.stockWrite.mock.calls[1][1])
  expect(api.stockWrite.mock.calls[0][1].body).toEqual({ expected_lock_version: 1, movement_type: 'issue', quantity_delta: -2, reason: '拍摄布景' })
})
test('permissions stay in the detail dialog and save after one explicit authorization', async () => {
  start(); const editor = await openAction('库存管理权限')
  await editor.findByRole('option', { name: '美术同学' })
  expect(screen.getAllByRole('dialog')).toHaveLength(1)
  expect((editor.getByRole('button', { name: '确认授权' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.change(editor.getByLabelText('选择成员'), { target: { value: 'member-1' } })
  expect(api.stockWrite).not.toHaveBeenCalled()
  fireEvent.click(editor.getByRole('radio', { name: /允许修改这项库存/ }))
  expect(editor.getByText(/已有禁用设置将改为允许/)).toBeTruthy()
  fireEvent.click(editor.getByLabelText('同时将这位成员设为耗材负责人'))
  fireEvent.click(editor.getByRole('button', { name: '确认授权' }))
  await waitFor(() => expect(api.stockWrite).toHaveBeenCalledTimes(1))
  expect(api.stockWrite.mock.calls[0][1].body).toMatchObject({ member_id: 'member-1', expected_member_lock_version: 3, permission_codes: ['stock.manage'], grant_capabilities: true, transfer_management: true })
  await screen.findByText('库存权限已更新。')
  expect(screen.getAllByRole('dialog')).toHaveLength(1)
  expect(screen.queryByRole('button', { name: '确认库存操作' })).toBeNull()
})

test('removing access does not grant capabilities or transfer responsibility', async () => {
  start(); const editor = await openAction('库存管理权限')
  await editor.findByRole('option', { name: '美术同学' })
  fireEvent.change(editor.getByLabelText('选择成员'), { target: { value: 'member-1' } })
  fireEvent.click(editor.getByRole('radio', { name: /允许修改这项库存/ }))
  fireEvent.click(editor.getByLabelText('同时将这位成员设为耗材负责人'))
  fireEvent.click(editor.getByRole('radio', { name: /移除这项库存的修改权限/ }))
  fireEvent.click(editor.getByRole('button', { name: '确认移除权限' }))
  await waitFor(() => expect(api.stockWrite).toHaveBeenCalledTimes(1))
  expect(api.stockWrite.mock.calls[0][1].body).toMatchObject({ permission_codes: [], grant_capabilities: false, transfer_management: false })
})

test('an uncertain permission update locks the same dialog and retries the original request', async () => {
  api.stockWrite.mockRejectedValueOnce(new AccountError('NETWORK_UNCONFIRMED'))
  start(); const editor = await openAction('库存管理权限')
  await editor.findByRole('option', { name: '美术同学' })
  fireEvent.change(editor.getByLabelText('选择成员'), { target: { value: 'member-1' } })
  fireEvent.click(editor.getByRole('radio', { name: /允许修改这项库存/ }))
  fireEvent.click(editor.getByRole('button', { name: '确认授权' }))
  const retry = await editor.findByRole('button', { name: '用原库存请求重试' })
  await waitFor(() => expect(retry.classList.contains('ant-btn-loading')).toBe(false))
  expect((editor.getByLabelText('选择成员') as HTMLSelectElement).disabled || editor.getByLabelText('选择成员').closest('fieldset')!.disabled).toBe(true)
  expect((editor.getByRole('button', { name: '库存与流水' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.click(retry)
  await waitFor(() => expect(api.stockWrite).toHaveBeenCalledTimes(2))
  expect(api.stockWrite.mock.calls[1][1]).toEqual(api.stockWrite.mock.calls[0][1])
})

test('stock conflict retains the reason and reads a new version before another write', async () => {
  api.stockWrite.mockRejectedValueOnce(new AccountError('VERSION_CONFLICT', 409))
  start(); const editor = await openAction('库存变动')
  fireEvent.change(editor.getByLabelText('变动原因'), { target: { value: '补充消耗' } })
  fireEvent.click(editor.getByRole('button', { name: '核对库存操作' })); fireEvent.click(editor.getByRole('button', { name: '确认库存操作' }))
  const reload = await editor.findByRole('button', { name: '读取最新库存并保留输入' })
  api.stock.mockResolvedValue({ ...row, lock_version: 4 })
  fireEvent.click(reload)
  await waitFor(() => expect(editor.getByLabelText('变动原因').closest('fieldset')!.disabled).toBe(false))
  expect((editor.getByLabelText('变动原因') as HTMLTextAreaElement).value).toBe('补充消耗')
  fireEvent.click(editor.getByRole('button', { name: '核对库存操作' })); fireEvent.click(editor.getByRole('button', { name: '确认库存操作' }))
  await waitFor(() => expect(api.stockWrite).toHaveBeenCalledTimes(2))
  expect(api.stockWrite.mock.calls[1][1].body.expected_lock_version).toBe(4)
})
