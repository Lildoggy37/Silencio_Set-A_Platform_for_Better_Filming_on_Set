import { expect, test, vi } from 'vitest'
import { createHttpClient } from './http'
import { createScriptClient } from './scripts'

test('file import uses multipart boundary generated by browser plus CSRF and idempotency headers', async () => {
  const fetcher = vi.fn().mockResolvedValueOnce(new Response(JSON.stringify({ data: { csrf_token: 'c'.repeat(64) } })))
    .mockResolvedValueOnce(new Response(JSON.stringify({ data: { script: { id: 'script' }, version: null } }), { status: 201 }))
  vi.stubGlobal('fetch', fetcher)
  const file = new File(['contents'], '剧本.pdf', { type: 'application/pdf' })
  await createScriptClient(createHttpClient()).importFile('crew', 'script', file, 3, 'import-key')
  const [url, options] = fetcher.mock.calls[1]
  expect(url).toBe('/api/v1/crews/crew/scripts/script/imports')
  expect(options.body).toBeInstanceOf(FormData)
  expect(options.body.get('expected_lock_version')).toBe('3')
  expect(options.body.get('file')).toBe(file)
  expect(options.headers['Content-Type']).toBeUndefined()
  expect(options.headers['X-CSRF-Token']).toBe('c'.repeat(64))
  expect(options.headers['Idempotency-Key']).toBe('import-key')
})
